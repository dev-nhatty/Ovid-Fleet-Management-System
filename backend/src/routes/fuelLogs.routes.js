const express = require('express');
const { requireRole } = require('../middleware/role.middleware');
const { ROLES } = require('../config/roles');
const { listFuelLogs, getFuelOptions, createFuelTransaction } = require('../controllers/fuelLogs.controller');
const router = express.Router();
router.use(requireRole(ROLES.MANAGER));
router.get('/', listFuelLogs);
router.get('/options', getFuelOptions);
router.post('/', createFuelTransaction);
module.exports = router;
